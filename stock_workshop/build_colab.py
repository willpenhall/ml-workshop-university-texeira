"""Build workshop_colab.ipynb: a self-contained Google Colab version of the workshop.

Colab cannot see this repo's files, so the generated notebook:
  1. installs omegaconf + hydra-core,
  2. writes every config file, engine.py and run.py with %%writefile,
  3. replays workshop.ipynb, turning the terminal commands into runnable `!python run.py ...` cells.

Re-run after editing any config, engine.py, run.py or workshop.ipynb:
    python build_colab.py
"""
import hashlib
import json
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE / "workshop_colab.ipynb"
REPO = "willpenhall/ml-workshop-university-texeira"
COLAB_URL = f"https://colab.research.google.com/github/{REPO}/blob/main/stock_workshop/{OUT.name}"

# Every file run.py / the notebook needs, in the order they are written in Colab.
WORKSPACE_FILES = [
    "conf/config.yaml",
    "conf/market/aapl.yaml",
    "conf/market/msft.yaml",
    "conf/market/tsla.yaml",
    "conf/strategy/sma_crossover.yaml",
    "conf/backtest/default.yaml",
    "engine.py",
    "run.py",
]

cells = []


def add(cell_type, text, tags=None):
    text = text.rstrip("\n")
    cell = {
        "cell_type": cell_type,
        "id": hashlib.sha1(f"{len(cells)}:{text}".encode()).hexdigest()[:8],
        "metadata": {"tags": tags} if tags else {},
        "source": text.splitlines(keepends=True),
    }
    if cell_type == "code":
        cell["execution_count"] = None
        cell["outputs"] = []
    cells.append(cell)


def command_cells(text):
    """Turn lines like `python run.py ... # note` (inside comments or a '''string''') into `!` cells."""
    for line in text.splitlines():
        line = re.sub(r"^\s*(#\s*(\d+\)\s*)?|''')", "", line).strip()
        if not line.startswith("python "):
            continue
        cmd, _, note = line.partition("#")
        add("code", (f"# {note.strip()}\n" if note.strip() else "") + f"!{cmd.strip()}")


# ---------------------------------------------------------------- intro + setup
add("markdown", f"""# OmegaConf / Hydra workshop (Google Colab)

[![Open In Colab](https://colab.research.google.com/assets/colab-badge.svg)]({COLAB_URL})

This notebook contains the whole `stock_workshop` folder, so nothing else needs to be uploaded.

**Run the cells in section 0 first** (or use *Runtime → Run all*). They install the libraries and write the config files, `engine.py` and `run.py` into Colab's file browser (folder icon on the left). Anywhere the workshop says to run a command in the terminal, this version gives you a ready-made `!python run.py ...` cell instead.

*Generated by `build_colab.py` from the repo files. Edit those, not this notebook.*""")

add("markdown", "## 0. Setup")
add("code", "%pip install -q omegaconf hydra-core")
add("code", """import os
from pathlib import Path

# Work inside ./stock_workshop (Colab starts in /content). Safe to re-run.
if Path.cwd().name != "stock_workshop":
    os.makedirs("stock_workshop", exist_ok=True)
    os.chdir("stock_workshop")
for group in ("market", "strategy", "backtest"):
    os.makedirs(f"conf/{group}", exist_ok=True)
print("Working directory:", Path.cwd())""")

add("markdown", """### 0.1 Workspace files
`conf/config.yaml` is the Hydra default list. Each group folder (`market`, `strategy`, `backtest`) holds the options for that group. `engine.py` is the backtest engine and `run.py` is the Hydra entry point.""")
for rel in WORKSPACE_FILES:
    add("code", f"%%writefile {rel}\n" + (HERE / rel).read_text(encoding="utf-8"))

add("code", """# Check: every file is in place and the engine imports
for rel in %r:
    assert Path(rel).is_file(), f"missing {rel}"
import engine
print("All files written. Simulated", len(engine.simulate_prices(100, 0.08, 0.25, 252, 42)), "prices.")""" % WORKSPACE_FILES)

# ---------------------------------------------------------------- the workshop itself
nb = json.loads((HERE / "workshop.ipynb").read_text(encoding="utf-8"))
for cell in nb["cells"]:
    src = "".join(cell["source"])
    if cell["cell_type"] == "markdown":
        add("markdown", src)
        if "'python run.py'" in src:          # the Hydra intro asks for a plain run
            add("code", "!python run.py")
    elif "python run.py" in src:              # terminal commands -> runnable cells
        command_cells(src)
    elif "# Break it on purpose" in src:      # each deliberate error gets its own cell
        body, _, breaks = src.partition("# Break it on purpose")
        add("code", body)
        header = "# Break it on purpose" + breaks.splitlines()[0]
        for i, line in enumerate(l for l in breaks.splitlines()[1:] if l.strip()):
            add("code", (header + "\n" if i == 0 else "") + line, tags=["raises-exception"])
    else:
        add("code", src)

notebook = {
    "cells": cells,
    "metadata": {
        "colab": {"provenance": [], "toc_visible": True},
        "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
        "language_info": {"name": "python"},
    },
    "nbformat": 4,
    "nbformat_minor": 5,
}
OUT.write_text(json.dumps(notebook, indent=1, ensure_ascii=False) + "\n", encoding="utf-8", newline="\n")
print(f"Wrote {OUT.name}: {len(cells)} cells")
